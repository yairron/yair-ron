/**
 * classifyAndComputePension.js
 * ============================
 * קובע מעמד משפחתי לצורך קצבת אזרח ותיק
 * ומחשב את קצבת הבסיס הסופית (לפני הפחתות הכנסה)
 *
 * קלט: אובייקט input + אובייקט constants (ערכים מ-nii-constants.json)
 * פלט: אובייקט תוצאה — ראה תיעוד בתחתית
 */

'use strict';

// ---------------------------------------------------------------------------
// קבועים פנימיים — גילאי סף לבדיקת הגדרת בן/בת זוג
// ---------------------------------------------------------------------------
const SPOUSE_MIN_AGE_FEMALE = 45;   // גיל מינימלי לבת זוג (אשת גבר)
const SPOUSE_MIN_AGE_MALE   = 50;   // גיל מינימלי לבן זוג (בעל אישה)
// גיל הזכאות המוחלט (70) — מעליו אין מבחן הכנסות לבן/בת זוג
// גיל פרישה לגבר (67)    — מעליו אין מבחן הכנסות לבת זוג
// שני הערכים נטענים מ-constants (retirement_age_male, retirement_age_unconditional)

// ---------------------------------------------------------------------------
// פונקציית עזר — שולפת ערך מספרי מאובייקט ה-constants
// ---------------------------------------------------------------------------
function getConst(constants, key) {
  const entry = constants[key];
  if (!entry) return null;
  const v = Number(entry.value !== undefined ? entry.value : entry);
  return Number.isFinite(v) ? v : null;
}

// ---------------------------------------------------------------------------
// ספירת ילדים תלויים
// ---------------------------------------------------------------------------
/**
 * סופרת ילדים תלויים לפי 5 הקטגוריות מהטופס.
 *
 * @param {object} children - אובייקט עם השדות:
 *   עד18        — ילדים עד גיל 18 (למעט נשואים)
 *   לומדים1820  — 18–20, לומדים על-תיכוניים / בעלי לקות למידה / קדם-צבאי
 *   שירות1824   — 18–24, שירות סדיר / לאומי / עתודה אקדמית
 *   מתנדבים1821 — 18–21, שירות התנדבותי (עד 12 חודשים)
 *
 * @returns {{ סהכ: number, מוגבל: number }}
 *   סהכ    — מספר ילדים כולל
 *   מוגבל  — min(סהכ, 2) לצורך בחירת מפתח קצבה
 */
function countDependentChildren(children) {
  const {
    עד18        = 0,
    לומדים1820  = 0,
    שירות1824   = 0,
    מתנדבים1821 = 0
  } = children || {};

  const סהכ = [עד18, לומדים1820, שירות1824, מתנדבים1821]
    .reduce((acc, n) => acc + (Number.isFinite(Number(n)) ? Math.max(0, Math.floor(Number(n))) : 0), 0);

  return {
    סהכ,
    מוגבל: Math.min(סהכ, 2)
  };
}

// ---------------------------------------------------------------------------
// הפונקציה הראשית
// ---------------------------------------------------------------------------
/**
 * classifyAndComputePension
 *
 * קובעת מעמד משפחתי ומחשבת קצבת בסיס סופית.
 *
 * @param {object} input — פרטי התובע/ת (ראה תיעוד שדות בתחתית)
 * @param {object} constants — אובייקט nii-constants.json (כולו, לא רק הערכים)
 *
 * @returns {object} — תוצאת חישוב (ראה תיעוד פלט בתחתית)
 */
function classifyAndComputePension(input, constants) {

  // ── 0. שליפת ערכי bii הדרושים ─────────────────────────────────────────
  const גילפרישהגבר     = getConst(constants, 'retirement_age_male');          // 67
  const גילזכאותמוחלט   = getConst(constants, 'retirement_age_unconditional'); // 70
  const תקרתהכנסתזוג    = getConst(constants, 'income_test_spouse_ceiling');   // 7,848
  const קצבהבסיסיחיד    = getConst(constants, 'pension_single_basic');         // 1,838
  const קצבהבסיסמעל80   = getConst(constants, 'pension_single_over80');        // 1,941
  const תוספתבןבתזוג    = getConst(constants, 'pension_spouse_supplement');    // 924
  const תוספתילד        = getConst(constants, 'pension_child_supplement');     // 581
  const שיעורוותקמקס    = getConst(constants, 'seniority_bonus_max');          // 50

  // ── 1. ולידציה בסיסית ──────────────────────────────────────────────────
  const { מין, מצבמשפחתי, גיל, ותק = 0, children, בןבתזוג } = input;

  if (!מין || מצבמשפחתי === undefined || מצבמשפחתי === null) {
    return _שגיאהטכנית('חסרים שדות חובה: מין ומצב משפחתי');
  }
  if (קצבהבסיסיחיד === null || תוספתבןבתזוג === null || תוספתילד === null || שיעורוותקמקס === null) {
    return _שגיאהטכנית('נתוני NII חסרים — לא ניתן לחשב');
  }

  // ── 2. האם נשוי/ידוע בציבור? ───────────────────────────────────────────
  const נשוי = (מצבמשפחתי === 'נשוי' || מצבמשפחתי === 'נשואה' || מצבמשפחתי === 'ידוע' || מצבמשפחתי === 'ידועה');

  // ── 3. בדיקת הגדרת בן/בת זוג ───────────────────────────────────────────
  let יש_תוספת_זוג = false;

  if (נשוי && בןבתזוג) {
    const {
      מתגורר,          // האם בן/בת הזוג גר/ה עם התובע/ת (true/false)
      משךנישואין,      // 'מעלשנה' | 'פחותמשנהעםילד' | 'פחותמשנהללאילד'
      גיל: גילזוג,    // גיל בן/בת הזוג במספר שנים
      הכנסה,           // הכנסת בן/בת הזוג בש"ח לחודש (כל המקורות)
      קצבה             // 'אין' | 'זקנה' | 'נכותכללית' | 'נכותעבודה'
    } = בןבתזוג;

    let עובר = true; // נניח מוכר — נפסול אם תנאי כלשהו נכשל

    // א. מגורים משותפים
    if (מתגורר !== true) {
      עובר = false;
    }

    // ב. משך נישואין
    if (עובר) {
      if (מין === 'גבר') {
        // לגבר: מעל שנה, או פחות משנה עם ילד משותף
        if (משךנישואין === 'פחותמשנהללאילד') עובר = false;
      } else {
        // לאישה עם בן זוג גבר: מעל שנה בלבד
        if (משךנישואין !== 'מעלשנה') עובר = false;
      }
    }

    // ג. גיל בן/בת הזוג + מבחן הכנסות
    if (עובר) {
      if (מין === 'גבר') {
        // בת זוג: מינימום גיל 45
        if (גילזוג < SPOUSE_MIN_AGE_FEMALE) {
          עובר = false;
        } else if (גילזוג < גילפרישהגבר) {
          // 45 עד 67: יש מבחן הכנסות ובדיקת קצבה פוסלת (כל קצבה — כולל זקנה)
          if (הכנסה > תקרתהכנסתזוג) עובר = false;
          if (עובר && קצבה !== 'אין') עובר = false;
        }
        // 67+: אין מבחן הכנסות — אבל כל קצבה עדיין פוסלת
        else if (קצבה !== 'אין') {
          עובר = false;
        }
      } else {
        // בן זוג: מינימום גיל 50
        if (גילזוג < SPOUSE_MIN_AGE_MALE) {
          עובר = false;
        } else if (גילזוג < גילזכאותמוחלט) {
          // 50 עד 70: יש מבחן הכנסות ובדיקת קצבה פוסלת (כל קצבה — כולל זקנה)
          if (הכנסה > תקרתהכנסתזוג) עובר = false;
          if (עובר && קצבה !== 'אין') עובר = false;
        } else {
          // 70+: אין מבחן הכנסות — אבל כל קצבה עדיין פוסלת
          if (קצבה !== 'אין') עובר = false;
        }
      }
    }

    יש_תוספת_זוג = עובר;
  }

  // ── 4. ספירת ילדים תלויים ──────────────────────────────────────────────
  const { סהכ: סהכילדים, מוגבל: ילדיםלחישוב } = countDependentChildren(children);

  // ── 5. חישוב קצבת הבסיס ────────────────────────────────────────────────
  // קצבה בסיסית לפי גיל התובע/ת
  const קצבהבסיסיתלפיגיל = (גיל >= 80) ? קצבהבסיסמעל80 : קצבהבסיסיחיד;

  const קצבהלפניוותק =
    קצבהבסיסיתלפיגיל
    + (יש_תוספת_זוג ? תוספתבןבתזוג : 0)
    + תוספתילד * ילדיםלחישוב;

  // תוספת ותק: מוגבלת למקסימום, מוזנת כמספר זוגי
  const ותקמחושב = Math.min(Math.max(0, Math.floor(ותק / 2) * 2), שיעורוותקמקס);
  const קצבתבסיססופית = Math.round(קצבהלפניוותק * (1 + ותקמחושב / 100));

  // ── 6. סף קצבה מינימלית (10% מקצבה בסיסית ליחיד) ─────────────────────
  //   קצבה הנמוכה מסף זה לא תשולם בפועל.
  //   האלגוריתם שמחשב הפחתות הכנסה צריך לדעת:
  //   אם לאחר ההפחתות הקצבה נמוכה מ-184 ₪ (בערך) — אין זכאות.
  const סףמינימלי = Math.round(קצבהבסיסיחיד * 0.1);

  // ── 7. בניית אובייקט תוצאה ─────────────────────────────────────────────
  return {
    // מעמד משפחתי
    יש_תוספת_זוג,
    תיאורהרכב: _תיאורהרכב(יש_תוספת_זוג, ילדיםלחישוב, מין),

    // ילדים
    סהכילדיםתלויים: סהכילדים,
    ילדיםלחישוב,

    // בניית הקצבה — פירוט לשקיפות
    קצבהבסיסיתלפיגיל,
    תוספתבןבתזוגמחושבת: יש_תוספת_זוג ? תוספתבןבתזוג : 0,
    תוספתילדיםמחושבת: תוספתילד * ילדיםלחישוב,
    קצבהלפניוותק,
    ותקמחושב,

    /**
     * קצבת הבסיס הסופית
     * ==================
     * זהו הסכום שממנו האלגוריתם מחשב את הזכאות:
     * ממנו מורידים את ההפחתות עקב הכנסות.
     * אם לאחר ההפחתות הסכום נמוך מ-סףמינימלי — אין זכאות לקצבה.
     */
    קצבתבסיססופית,

    /**
     * סף מינימלי לזכאות
     * ==================
     * קצבה הנמוכה מסכום זה אינה משולמת.
     * ערך קבוע: 10% מהקצבה הבסיסית ליחיד/ה.
     */
    סףמינימלי,

    // מטא
    שגיאהטכנית: null
  };
}

// ---------------------------------------------------------------------------
// פונקציות עזר פנימיות
// ---------------------------------------------------------------------------

function _שגיאהטכנית(הודעה) {
  return {
    יש_תוספת_זוג: false,
    תיאורהרכב: null,
    סהכילדיםתלויים: 0,
    ילדיםלחישוב: 0,
    קצבהבסיסיתלפיגיל: 0,
    תוספתבןבתזוגמחושבת: 0,
    תוספתילדיםמחושבת: 0,
    קצבהלפניוותק: 0,
    ותקמחושב: 0,
    קצבתבסיססופית: 0,
    סףמינימלי: 0,
    שגיאהטכנית: הודעה
  };
}

function _תיאורהרכב(יש_תוספת_זוג, ילדים, מין) {
  const בסיס = יש_תוספת_זוג ? 'זוג' : 'יחיד/ה';
  if (ילדים === 0) return בסיס;
  if (ילדים === 1) return `${בסיס} + ילד אחד`;
  return `${בסיס} + שני ילדים`;
}

